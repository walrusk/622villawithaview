		<p>An awesome shop in downtown Charlotte Amalie is Local Color. Look out for it. They have some really neat stuff. Havensight, Vendor's Plaza, Main Street in Charlotte Amalie and at the waterfront at Yacht Haven Grande are some of the great places to shop.
