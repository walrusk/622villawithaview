		<p><strong>Shopping Tips:</strong><br>
			<ul class="list">
				<li>Save your swimwear for the beach. It is considered taboo to wear swimsuits only or to walk about bareback anywhere but the beach or poolside. You will receive a much friendlier reception from sales people if you are covered up when walking around shopping areas and entering stores.</li>
				<li>There are a lot of jewelry stores on St. Thomas. Many of the family run stores will bargain or haggle on the price, so be prepared to make offers lower than the original or ticket price. Larger stores also might give discounts but to a lesser degree, in any case its worth it to ask. Also if you have time then shop around, you might very well find the same item in another store.</li>
				<li>Say 'Good _____ (Morning, Day, Afternoon)' to salespeople before starting a conversation. Locals are very greeting conscious and this small gesture goes a long way.</li>
